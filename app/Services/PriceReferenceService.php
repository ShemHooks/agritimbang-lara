<?php

namespace App\Services;

use App\Models\PriceReference;
use App\Models\User;
use App\Notifications\SystemAlertNotification;
use Illuminate\Contracts\Pagination\LengthAwarePaginator;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

class PriceReferenceService
{
    public function getPriceReferences(
        User $user,
        array $filters = []
    ): LengthAwarePaginator {
        $municipalityId = $this->municipalityId($user);

        return PriceReference::query()
            ->where('municipality_id', $municipalityId)
            ->when(
                $filters['status'] ?? null,
                fn($query, $status) =>
                    $query->where('status', $status)
            )
            ->when(
                $filters['species_id'] ?? null,
                fn($query, $speciesId) =>
                    $query->where('species_id', $speciesId)
            )
            ->when(
                $filters['breed_id'] ?? null,
                fn($query, $breedId) =>
                    $query->where('breed_id', $breedId)
            )
            ->when(
                $filters['sale_purpose'] ?? null,
                fn($query, $salePurpose) =>
                    $query->where('sale_purpose', $salePurpose)
            )
            ->when(
                $filters['barangay_id'] ?? null,
                fn($query, $barangayId) =>
                    $query->where('barangay_id', $barangayId)
            )
            ->with([
                'municipality',
                'barangay',
                'species',
                'breed',
                'submitter',
            ])
            // Submission history must follow the actual submission time, not the
            // price's effective date. Drafts have no submitted_at, so fall back
            // to created_at while keeping them in a predictable chronological order.
            ->orderByRaw('COALESCE(submitted_at, created_at) DESC')
            ->orderByDesc('created_at')
            ->orderByDesc('id')
            ->paginate(20);
    }

    public function getPriceReference(
        User $user,
        PriceReference $priceReference
    ): PriceReference {
        $this->ensureSameMunicipality($user, $priceReference);

        return $priceReference->load([
            'municipality',
            'barangay',
            'species',
            'breed',
            'submitter',
            'reviewer',
            'approver',
            'validationLogs.performer',
        ]);
    }

    public function create(
        User $user,
        array $data
    ): PriceReference {
        $municipalityId = $this->municipalityId($user);

        return DB::transaction(function () use ($user, $data, $municipalityId) {
            $recommendation = null;
            if (!empty($data['recommendation_id'])) {
                $recommendation = \App\Models\WeeklyPriceRecommendation::whereKey($data['recommendation_id'])->where('municipality_id', $municipalityId)->lockForUpdate()->firstOrFail();
                if ($recommendation->used_by !== $user->id || !$recommendation->used_at || $recommendation->status !== 'used' || $recommendation->price_reference_id) {
                    throw ValidationException::withMessages(['recommendation_id' => 'This recommendation was not reserved by your account.']);
                }
                $data['species_id'] = $recommendation->species_id;
                $data['sale_purpose'] = $recommendation->sale_purpose;
                $data['price_per_kg'] = $recommendation->recommended_price;
                $data['effective_from'] = $recommendation->week_start->copy()->addDays(7)->toDateString();
                $data['effective_to'] = $recommendation->week_end->copy()->addDays(7)->toDateString();
                $data['source'] = 'AgriTimbang Weekly Price Recommendation Engine';
                $data['remarks'] = trim('Generated by the AgriTimbang Weekly Price Recommendation Engine. Recommendation ID: '.$recommendation->id);
            }
            $priceReference = PriceReference::create([
                'municipality_id' => $municipalityId,
                'barangay_id' => $data['barangay_id'] ?? null,
                'species_id' => $data['species_id'],
                'breed_id' => $data['breed_id'] ?? null,

                'sale_purpose' => $data['sale_purpose'],
                'reference_category' => $data['reference_category'] ?? ucfirst($data['sale_purpose']),
                'price_per_kg' => $data['price_per_kg'],
                'price_min_per_unit' => $data['price_min_per_unit'] ?? $data['price_per_kg'],
                'price_max_per_unit' => $data['price_max_per_unit'] ?? $data['price_per_kg'],
                'price_unit' => $data['price_unit'] ?? 'PHP/kg',

                'effective_from' => $data['effective_from'],
                // Enforce the weekly Monday-Sunday window on the server too.
                'effective_to' => \Carbon\CarbonImmutable::parse($data['effective_from'])
                    ->endOfWeek(\Carbon\Carbon::SUNDAY)
                    ->toDateString(),

                'source' => $data['source'],
                'remarks' => $data['remarks'] ?? null,

                'status' => 'draft',

                // Record the authenticated LGU Encoder.
                'submitted_by' => $user->id,
            ]);
            if ($recommendation) { $recommendation->update(['price_reference_id' => $priceReference->id]); }

            return $priceReference->load([
                'municipality',
                'barangay',
                'species',
                'breed',
                'submitter',
            ]);
        });
    }

    public function update(
        User $user,
        PriceReference $priceReference,
        array $data
    ): PriceReference {
        $this->ensureSameMunicipality($user, $priceReference);

        if ($priceReference->status !== 'draft') {
            throw ValidationException::withMessages([
                'status' =>
                    'Only draft price references can be edited.',
            ]);
        }

        $effectiveFrom = $data['effective_from'] ?? $priceReference->effective_from->toDateString();
        $data['effective_from'] = $effectiveFrom;
        // Ignore any manually supplied end date; the weekly period ends Sunday.
        $data['effective_to'] = \Carbon\CarbonImmutable::parse($effectiveFrom)
            ->endOfWeek(\Carbon\Carbon::SUNDAY)
            ->toDateString();

        $priceReference->update($data);

        return $priceReference->fresh()->load([
            'municipality',
            'barangay',
            'species',
            'breed',
        ]);
    }

    public function submit(
        User $user,
        PriceReference $priceReference
    ): PriceReference {
        $this->ensureSameMunicipality($user, $priceReference);

        if ($priceReference->status !== 'draft') {
            throw ValidationException::withMessages([
                'status' =>
                    'Only draft price references can be submitted.',
            ]);
        }

        return DB::transaction(function () use ($user, $priceReference) {
            $priceReference->update([
                'status' => 'pending_review',
                'submitted_by' => $user->id,
                'submitted_at' => now(),
            ]);

            $priceReference->validationLogs()->create([
                'from_status' => 'draft',
                'to_status' => 'pending_review',
                'action' => 'submitted',
                'performed_by' => $user->id,
            ]);

            $authorityUsers = User::query()
                ->where('status', 'active')
                ->whereHas('roles', fn ($q) => $q->where('slug', 'lgu_authority'))
                ->whereHas('lguOfficerProfile', fn ($q) => $q->where('municipality_id', $priceReference->municipality_id))
                ->get();
            foreach ($authorityUsers as $authorityUser) {
                $authorityUser->notify(new SystemAlertNotification(
                    'price.submitted',
                    'Bag-ong presyo nga naghulat og review',
                    'A livestock price reference has been submitted and is waiting for your approval.',
                    (string) $priceReference->municipality_id,
                    'price_reference',
                    (string) $priceReference->id
                ));
            }

            return $priceReference->fresh()->load([
                'municipality',
                'barangay',
                'species',
                'breed',
                'submitter',
                'validationLogs.performer',
            ]);
        });
    }

    private function municipalityId(User $user): string
    {
        $municipalityId = $user->lguOfficerProfile?->municipality_id;

        if (!$municipalityId) {
            throw ValidationException::withMessages([
                'user' =>
                    'The authenticated user does not have an assigned municipality.',
            ]);
        }

        return $municipalityId;
    }

    private function ensureSameMunicipality(
        User $user,
        PriceReference $priceReference
    ): void {
        if (
            $priceReference->municipality_id !==
            $this->municipalityId($user)
        ) {
            abort(404);
        }
    }
}